# 写作质量标准
WRITING_QUALITY_GUIDELINES = """<writing_quality>
写作质量标准：

1. **开篇吸引力**：第一章/第一幕必须在3句话内抓住读者注意力
2. **场景描写**：使用五感描写（视觉/听觉/嗅觉/触觉/味觉），避免平铺直叙
3. **对话自然**：对话要符合角色性格和身份，避免"说教式"对话
4. **节奏控制**：紧张段落用短句快节奏，抒情段落用长句慢节奏
5. **情感共鸣**：角色的情感变化要有铺垫，避免突兀
6. **避免俗套**：避免过度使用陈词滥调和套路化描写
7. **角色一致性**：角色的语言和行为要前后一致
</writing_quality>"""

